import { promises as fs } from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const srcDir = path.join(projectRoot, "src");
const outputPath = path.join(srcDir, "icons", "generatedCollections.ts");

const COLLECTION_CONFIG = {
  "material-symbols": {
    importName: "materialSymbols",
    source: path.join(
      projectRoot,
      "node_modules",
      "@iconify-json",
      "material-symbols",
      "icons.json",
    ),
  },
  "simple-icons": {
    importName: "simpleIcons",
    source: path.join(
      projectRoot,
      "node_modules",
      "@iconify-json",
      "simple-icons",
      "icons.json",
    ),
  },
};

const ICON_PATTERN = /["'`](material-symbols|simple-icons):([^"'`]+)["'`]/g;

async function collectFiles(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const entryPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectFiles(entryPath)));
      continue;
    }
    if (entryPath.endsWith(".ts") || entryPath.endsWith(".tsx")) {
      files.push(entryPath);
    }
  }

  return files;
}

async function collectUsedIcons() {
  const files = await collectFiles(srcDir);
  const usedIcons = new Map(
    Object.keys(COLLECTION_CONFIG).map((prefix) => [prefix, new Set()]),
  );

  for (const file of files) {
    const content = await fs.readFile(file, "utf8");
    for (const match of content.matchAll(ICON_PATTERN)) {
      usedIcons.get(match[1])?.add(match[2]);
    }
  }

  return usedIcons;
}

async function loadCollection(filePath) {
  return JSON.parse(await fs.readFile(filePath, "utf8"));
}

function pickCollectionSubset(collection, names) {
  return {
    prefix: collection.prefix,
    width: collection.width,
    height: collection.height,
    icons: Object.fromEntries(
      names
        .filter((name) => collection.icons[name])
        .map((name) => [name, collection.icons[name]]),
    ),
    aliases: Object.fromEntries(
      Object.entries(collection.aliases ?? {}).filter(([name]) => names.includes(name)),
    ),
  };
}

function createModuleSource(subsets) {
  const serializedSubsets = JSON.stringify(subsets, null, 2);

  return `import { addCollection } from "@iconify/react";

// This file is generated by scripts/generate-icon-collections.mjs.
const iconCollections = ${serializedSubsets} as const;

let registered = false;

export function registerAppIcons() {
  if (registered) return;
  registered = true;

  for (const collection of iconCollections) {
    addCollection(collection as never);
  }
}
`;
}

async function main() {
  const usedIcons = await collectUsedIcons();
  const missingIcons = [];
  const subsets = [];

  for (const [prefix, config] of Object.entries(COLLECTION_CONFIG)) {
    const iconNames = Array.from(usedIcons.get(prefix) ?? []).sort();
    const collection = await loadCollection(config.source);
    const subset = pickCollectionSubset(collection, iconNames);

    for (const name of iconNames) {
      if (!subset.icons[name] && !subset.aliases?.[name]) {
        missingIcons.push(`${prefix}:${name}`);
      }
    }

    subsets.push(subset);
  }

  if (missingIcons.length > 0) {
    console.warn("Missing icon definitions:", missingIcons.join(", "));
  }

  await fs.writeFile(outputPath, createModuleSource(subsets));
}

await main();
